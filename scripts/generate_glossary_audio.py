def get_audio_duration(file_path):
    with wave.open(str(file_path), 'rb') as w:
        frames = w.getnframes()
        rate = w.getframerate()
        return frames / float(rate)

def main():
    print(f"Total terms to process: {len(TERMS)}")
    
    # 1. Generate 5-second silence WAV at 24000 Hz, mono, s16le
    silence_wav = TEMP_DIR / "silence_5s.wav"
    subprocess.run([
        "ffmpeg", "-f", "lavfi", "-i", "anullsrc=r=24000:cl=mono",
        "-t", str(PAUSE_SEC), "-y", str(silence_wav)
    ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    
    term_durations = []
    current_time = 0.0
    concat_list_file = TEMP_DIR / "concat_list.txt"
    
    with open(concat_list_file, "w") as f_list:
        for idx, item in enumerate(TERMS):
            tid = item["id"]
            wav_path = TEMP_DIR / f"{idx:02d}_{tid}.wav"
            mp3_term_path = TERMS_AUDIO_DIR / f"{tid}.mp3"
            
            print(f"[{idx+1}/{len(TERMS)}] Synthesizing: {item['name']}...")
            
            # Synthesize term audio
            cmd = [
                KOKORO_CLI, "synthesize", item["spoken"],
                "--voice", VOICE,
                "--output", str(wav_path)
            ]
            subprocess.run(cmd, check=True)
            
            dur = get_audio_duration(wav_path)
            start_time = current_time
            end_time = current_time + dur
            
            # Save individual term MP3 for quick per-term playback
            subprocess.run([
                "ffmpeg", "-i", str(wav_path), "-b:a", "96k", "-y", str(mp3_term_path)
            ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            
            item["audio_start"] = round(start_time, 2)
            item["audio_end"] = round(end_time, 2)
            item["duration"] = round(dur, 2)
            item["term_audio_url"] = f"assets/audio/terms/{tid}.mp3"
            
            # Add to concat list
            f_list.write(f"file '{wav_path}'\n")
            
            # Add 5 sec silence after every term except the very last one
            if idx < len(TERMS) - 1:
                f_list.write(f"file '{silence_wav}'\n")
                current_time = end_time + PAUSE_SEC
            else:
                current_time = end_time
                
            print(f"   -> Duration: {dur:.2f}s | Start: {start_time:.2f}s | End: {end_time:.2f}s")

    print(f"\nConcatenating full audio (Total estimated duration: {current_time:.2f}s = {current_time/60:.2f} min)...")
    master_wav = TEMP_DIR / "master_glossary.wav"
    master_mp3 = AUDIO_DIR / "glossary-complete.mp3"
    
    subprocess.run([
        "ffmpeg", "-f", "concat", "-safe", "0", "-i", str(concat_list_file),
        "-c", "copy", "-y", str(master_wav)
    ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    
    # Convert master WAV to high-quality compressed MP3 for web playback
    subprocess.run([
        "ffmpeg", "-i", str(master_wav), "-b:a", "128k", "-y", str(master_mp3)
    ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    
    total_master_dur = get_audio_duration(master_wav)
    print(f"Master MP3 created: {master_mp3} ({total_master_dur:.2f}s)")
    
    # Write glossary data to JS file
    js_output_path = BASE_DIR / "assets" / "glossary-data.js"
    with open(js_output_path, "w", encoding="utf-8") as f_js:
        f_js.write("// Comprehensive Business Measures Glossary Data with Audio Timestamps\n")
        f_js.write(f"window.glossaryAudioUrl = 'assets/audio/glossary-complete.mp3';\n")
        f_js.write(f"window.glossaryTotalDuration = {round(total_master_dur, 2)};\n")
        f_js.write(f"window.glossaryPauseDuration = {PAUSE_SEC};\n")
        f_js.write("window.glossaryTerms = ")
        json.dump(TERMS, f_js, indent=2)
        f_js.write(";\n")
        
    print(f"Data saved to {js_output_path}")
    print("Done!")

if __name__ == "__main__":
    main()
